//go:build unix

package crontab

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"
)

const (
	backupDirMode  = 0o700
	backupFileMode = 0o600
	stampLayout    = "20060102T150405.000000000Z"
	doneSuffix     = ".done"
)

// Backups keeps the content that was replaced by Apply.
type Backups struct {
	Dir string
	Now func() time.Time
}

// Result describes what Apply or Undo did.
type Result struct {
	Changed    bool
	BackupPath string
	Plan       Plan
}

// Entry is one saved backup.
type Entry struct {
	BackupPath    string
	MetaPath      string
	AppliedSHA256 string
	Original      string
}

type meta struct {
	Target         string `json:"target"`
	AppliedSHA256  string `json:"appliedSha256"`
	OriginalSHA256 string `json:"originalSha256"`
	CreatedAt      string `json:"createdAt"`
}

var installedHeader = regexp.MustCompile(`^# (DO NOT EDIT THIS FILE|\(.* installed on .*\)|\(Cron version .*\))`)

func normalize(content string) string {
	lines := strings.Split(content, "\n")
	for len(lines) > 0 && installedHeader.MatchString(lines[0]) {
		lines = lines[1:]
	}
	return strings.TrimRight(strings.Join(lines, "\n"), " \t\r\n")
}

func digest(content string) string {
	sum := sha256.Sum256([]byte(normalize(content)))
	return hex.EncodeToString(sum[:])
}

// Save records the original content of target and the content that replaces it.
func (b *Backups) Save(target, original, applied string) (Entry, error) {
	if err := os.MkdirAll(b.Dir, backupDirMode); err != nil {
		return Entry{}, fmt.Errorf("create backup directory %s: %w", b.Dir, errors.Unwrap(err))
	}
	stamp := b.Now().UTC().Format(stampLayout)
	for n := 0; ; n++ {
		id := stamp
		if n > 0 {
			id = fmt.Sprintf("%s-%d", stamp, n)
		}
		backup := filepath.Join(b.Dir, id+".bak")
		f, err := os.OpenFile(backup, os.O_WRONLY|os.O_CREATE|os.O_EXCL, backupFileMode) //nolint:gosec // the path is inside the private backup directory
		if errors.Is(err, os.ErrExist) {
			continue
		}
		if err != nil {
			return Entry{}, fmt.Errorf("create backup %s: %w", backup, errors.Unwrap(err))
		}
		_, werr := f.WriteString(original)
		if cerr := f.Close(); werr == nil {
			werr = cerr
		}
		if werr != nil {
			_ = os.Remove(backup)
			return Entry{}, fmt.Errorf("write backup %s: %w", backup, werr)
		}
		metaPath := filepath.Join(b.Dir, id+".json")
		data, _ := json.Marshal(meta{Target: target, AppliedSHA256: digest(applied), OriginalSHA256: digest(original), CreatedAt: b.Now().UTC().Format(time.RFC3339)})
		if err := os.WriteFile(metaPath, data, backupFileMode); err != nil {
			_ = os.Remove(backup)
			return Entry{}, fmt.Errorf("write backup metadata: %w", errors.Unwrap(err))
		}
		return Entry{BackupPath: backup, MetaPath: metaPath, AppliedSHA256: digest(applied), Original: original}, nil
	}
}

// Latest returns the newest unconsumed backup of target.
func (b *Backups) Latest(target string) (Entry, error) {
	files, err := filepath.Glob(filepath.Join(b.Dir, "*.json"))
	if err != nil {
		return Entry{}, ErrNoBackup
	}
	ids := make([]string, 0, len(files))
	for _, f := range files {
		ids = append(ids, strings.TrimSuffix(filepath.Base(f), ".json"))
	}
	sort.Sort(sort.Reverse(sort.StringSlice(ids)))
	for _, id := range ids {
		metaPath := filepath.Join(b.Dir, id+".json")
		raw, err := os.ReadFile(metaPath) //nolint:gosec // the path is inside the private backup directory
		if err != nil {
			continue
		}
		var m meta
		if json.Unmarshal(raw, &m) != nil || m.Target != target {
			continue
		}
		backup := filepath.Join(b.Dir, id+".bak")
		original, err := os.ReadFile(backup) //nolint:gosec // the path is inside the private backup directory
		if err != nil {
			continue
		}
		return Entry{BackupPath: backup, MetaPath: metaPath, AppliedSHA256: m.AppliedSHA256, Original: string(original)}, nil
	}
	return Entry{}, ErrNoBackup
}

// Consume marks a backup as used so it is not restored twice.
func (b *Backups) Consume(e Entry) error {
	return os.Rename(e.MetaPath, e.MetaPath+doneSuffix)
}

// Apply wraps the jobs of the store, keeping a backup, and verifies the result.
func Apply(store Store, backups *Backups, opts Options) (Result, error) {
	current, err := store.Read()
	if err != nil {
		return Result{}, err
	}
	plan, err := Build(current, opts)
	if err != nil {
		return Result{}, err
	}
	if !plan.Changed() {
		return Result{Plan: plan}, nil
	}
	entry, err := backups.Save(store.Target(), current, plan.Output)
	if err != nil {
		return Result{}, err
	}
	if err := store.Write(plan.Output); err != nil {
		_ = os.Remove(entry.BackupPath)
		_ = os.Remove(entry.MetaPath)
		return Result{}, fmt.Errorf("install the new crontab (the crontab is unchanged): %w", err)
	}
	if err := verify(store, plan.Output); err != nil {
		if rollbackErr := restore(store, current); rollbackErr != nil {
			return Result{}, fmt.Errorf("%w; restoring the original also failed (%w), the original is saved in %s",
				err, rollbackErr, entry.BackupPath)
		}
		_ = backups.Consume(entry)
		return Result{}, fmt.Errorf("%w; the original crontab was restored", err)
	}
	return Result{Changed: true, BackupPath: entry.BackupPath, Plan: plan}, nil
}

func verify(store Store, want string) error {
	got, err := store.Read()
	if err != nil {
		return fmt.Errorf("verification failed, cannot read the crontab back: %w", err)
	}
	if normalize(got) != normalize(want) {
		return errors.New("verification failed, the crontab read back differs from what was written")
	}
	return nil
}

func restore(store Store, content string) error {
	if err := store.Write(content); err != nil {
		return err
	}
	return verify(store, content)
}

// Undo restores the content saved by the latest Apply of the store.
func Undo(store Store, backups *Backups, force bool) (Result, error) {
	entry, err := backups.Latest(store.Target())
	if err != nil {
		return Result{}, err
	}
	current, err := store.Read()
	if err != nil {
		return Result{}, err
	}
	if digest(current) != entry.AppliedSHA256 && !force {
		return Result{}, fmt.Errorf("%w: it differs from what apply wrote, use --force to restore %s anyway "+
			"(later changes are lost)", ErrModified, entry.BackupPath)
	}
	if err := restore(store, entry.Original); err != nil {
		return Result{}, fmt.Errorf("restore the crontab: %w", err)
	}
	_ = backups.Consume(entry)
	return Result{Changed: true, BackupPath: entry.BackupPath}, nil
}
